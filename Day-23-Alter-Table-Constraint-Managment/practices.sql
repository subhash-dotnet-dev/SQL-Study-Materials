-- ============================================================
-- 1. CREATE TABLE FOR PRACTICE
-- ============================================================

CREATE TABLE EMP77
(
    EMPNO INT,
    ENAME VARCHAR(10),
    SAL MONEY,
    EMAILID VARCHAR(50),
    DNO INT
);

-- Check table data
SELECT * FROM EMP77;


-- ============================================================
-- 2. INSERT SAMPLE DATA
-- ============================================================

INSERT INTO EMP77 VALUES
(100, 'A', 5000, 'a@gmail.com', 10),
(101, 'B', 4000, 'b@gmail.com', 20),
(102, 'C', 2500, 'c@gmail.com', 10),
(103, 'D', 3500, 'd@gmail.com', NULL);

SELECT * FROM EMP77;


-- ============================================================
-- 3. ADD CHECK CONSTRAINT
-- ============================================================

-- Salary must be greater than or equal to 3000

ALTER TABLE EMP77
ADD CHECK (SAL >= 3000);


-- NOTE:
-- This statement may fail because existing employee C
-- has salary 2500.

-- Check existing data
SELECT *
FROM EMP77
WHERE SAL < 3000;


-- ============================================================
-- 4. ADD CHECK CONSTRAINT WITH NOCHECK
-- ============================================================

-- Existing data will not be validated.

ALTER TABLE EMP77
WITH NOCHECK
ADD CHECK (SAL >= 3000);


-- Test new data

INSERT INTO EMP77
VALUES (104, 'E', 2000, 'e@gmail.com', 10);

-- The new invalid record should be rejected.


INSERT INTO EMP77
VALUES (105, 'F', 5000, 'f@gmail.com', 10);

-- Valid record should be accepted.


-- ============================================================
-- 5. CREATE DEPARTMENT TABLE
-- ============================================================

CREATE TABLE DEPT77
(
    DEPTNO INT PRIMARY KEY,
    DNAME VARCHAR(20)
);


INSERT INTO DEPT77 VALUES
(10, 'HR'),
(20, 'IT'),
(30, 'SALES');

SELECT * FROM DEPT77;


-- ============================================================
-- 6. ADD FOREIGN KEY
-- ============================================================

ALTER TABLE EMP77
ADD FOREIGN KEY (DNO)
REFERENCES DEPT77(DEPTNO);


-- Valid Foreign Key value

INSERT INTO EMP77
VALUES (106, 'G', 4000, 'g@gmail.com', 10);


-- Invalid Foreign Key value

INSERT INTO EMP77
VALUES (107, 'H', 4000, 'h@gmail.com', 99);

-- ERROR because 99 does not exist in DEPT77.


-- NULL is allowed in FK column

INSERT INTO EMP77
VALUES (108, 'I', 4000, 'i@gmail.com', NULL);


-- ============================================================
-- 7. ADD UNIQUE CONSTRAINT
-- ============================================================

ALTER TABLE EMP77
ADD UNIQUE (EMAILID);


-- Duplicate email should fail

INSERT INTO EMP77
VALUES (109, 'J', 4000, 'a@gmail.com', 10);


-- Unique email should work

INSERT INTO EMP77
VALUES (110, 'K', 4000, 'k@gmail.com', 20);


-- ============================================================
-- 8. ALTER COLUMN — NULL TO NOT NULL
-- ============================================================

-- First check NULL values

SELECT *
FROM EMP77
WHERE ENAME IS NULL;


-- Change ENAME to NOT NULL

ALTER TABLE EMP77
ALTER COLUMN ENAME VARCHAR(10) NOT NULL;


-- Test NULL value

INSERT INTO EMP77
VALUES (111, NULL, 4000, 'l@gmail.com', 10);

-- ERROR because ENAME is NOT NULL.


-- ============================================================
-- 9. ADD PRIMARY KEY
-- ============================================================

-- EMPNO must first be NOT NULL.

ALTER TABLE EMP77
ALTER COLUMN EMPNO INT NOT NULL;


-- Add Primary Key

ALTER TABLE EMP77
ADD PRIMARY KEY (EMPNO);


-- Test duplicate Primary Key

INSERT INTO EMP77
VALUES (100, 'X', 5000, 'x@gmail.com', 10);

-- ERROR because EMPNO 100 already exists.


