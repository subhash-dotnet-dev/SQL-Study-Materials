-- ============================================================
-- 12. CONSTRAINT DEPENDENCY PRACTICE
-- ============================================================

-- EMP77.DNO references DEPT77.DEPTNO.

-- Try dropping Primary Key:

ALTER TABLE DEPT77
DROP CONSTRAINT PK__DEPT77__;


-- This will fail if EMP77 has a Foreign Key
-- referencing DEPT77.DEPTNO.


-- ============================================================
-- 13. DROP FOREIGN KEY FIRST
-- ============================================================

-- Find the Foreign Key name:

SELECT
    name,
    type_desc
FROM sys.objects
WHERE parent_object_id = OBJECT_ID('EMP77');


-- Then drop the Foreign Key:

ALTER TABLE EMP77
DROP CONSTRAINT FK_EMP77_DEPT77;


-- Now Primary Key can be dropped if no other dependency exists.


-- ============================================================
-- 14. DROP PRIMARY KEY
-- ============================================================

ALTER TABLE DEPT77
DROP CONSTRAINT PK_DEPT77;


-- ============================================================
-- 15. DROP TABLE DEPENDENCY
-- ============================================================

-- If a Foreign Key references DEPT77,
-- dropping DEPT77 directly will fail.

DROP TABLE DEPT77;


-- Correct approach:
-- 1. Drop Foreign Key
-- 2. Drop Primary Key if required
-- 3. Drop Parent Table


-- ============================================================
-- 16. TRUNCATE TABLE DEPENDENCY
-- ============================================================

-- A referenced parent table cannot be truncated
-- while a Foreign Key dependency exists.

TRUNCATE TABLE DEPT77;


-- ============================================================
-- 17. FIND ALL CONSTRAINTS OF A TABLE
-- ============================================================

SELECT
    name AS ConstraintName,
    type_desc AS ConstraintType
FROM sys.objects
WHERE parent_object_id = OBJECT_ID('EMP77');


